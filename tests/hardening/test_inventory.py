"""Read-only inventory regression tests; compare to independent mbox reference."""
import importlib.util
import io
import os
from pathlib import Path
import sys
import tempfile
import unittest
from unittest import mock

ROOT = Path(__file__).resolve().parents[2]
ENGINE = ROOT / "examples/autogenerated/safe-filing"
sys.path.insert(0, str(ENGINE))
import framing
import spec_list

spec = importlib.util.spec_from_file_location("spec_list_inventory", ROOT / "bin/spec-list-inventory.py")
inventory = importlib.util.module_from_spec(spec)
spec.loader.exec_module(inventory)


class InventoryTests(unittest.TestCase):
    def setUp(self):
        self.tmp = tempfile.TemporaryDirectory()
        self.path = Path(self.tmp.name) / "incoming"

    def tearDown(self):
        self.tmp.cleanup()

    def check_bytes(self, raw):
        self.path.write_bytes(raw)
        before = self.path.stat()
        output = inventory.scan(self.path, 2)
        reference = list(framing.records(io.BytesIO(raw)))
        marked = [record for record in reference
                  if spec_list.evidence(framing.fields(record.header))]
        self.assertTrue(output["stable"])
        self.assertEqual(output["total"], len(reference))
        self.assertEqual(output["selected"], len(marked))
        self.assertEqual(output["selected_octets"],
                         sum(record.end - record.start for record in marked))
        for name in spec_list.SEARCH_HEADERS:
            self.assertEqual(output["by_header"][name],
                sum(any(key.lower() == name for key, value in
                        spec_list.evidence(framing.fields(record.header))) for record in reference))
        self.assertEqual(self.path.read_bytes(), raw)
        after = self.path.stat()
        self.assertEqual((before.st_ino, before.st_size, before.st_mtime_ns),
                         (after.st_ino, after.st_size, after.st_mtime_ns))
        self.assertEqual(os.listdir(self.tmp.name), ["incoming"])
        rendered = io.StringIO()
        inventory.report(output, rendered)
        self.assertIn("status\tSTABLE", rendered.getvalue())
        self.assertNotIn("\x1b", rendered.getvalue())

    def test_shared_fixtures_against_reference(self):
        for name in ("empty.mbox", "spec-list-selection.mbox", "header-corners.mbox",
                     "mboxo-lf.mbox", "mboxo-crlf.mbox", "unescaped-from-splits.mbox",
                     "dedup-corners.mbox", "copy-preservation.mbox"):
            with self.subTest(fixture=name):
                self.check_bytes((ROOT / "fixtures" / name).read_bytes())

    def test_spec_list_manifest(self):
        data = (ROOT / "fixtures/spec-list-selection.mbox").read_bytes()
        self.path.write_bytes(data)
        result = inventory.scan(self.path, 100)
        self.assertEqual((result["total"], result["selected"]), (14, 9))
        self.assertEqual(len(result["first"]), 9)
        self.assertEqual(result["last"], [])

    def test_duplicate_occurrences_and_bounded_large_body(self):
        item = (b"From x Tue Jan 1 00:00:00 2024\n"
                b"Subject: SPEC-LIST\nMessage-ID: <same>\n\n" + b"x" * (3 * inventory.CHUNK) + b"\n")
        self.check_bytes(item + item)

    def test_body_only_wrong_header_and_escaped_terminal(self):
        raw = (b"From a Tue Jan 1 00:00:00 2024\n"
               b"X-Any: SPEC-LIST\nSubject: ordinary\n\nSPEC-LIST only in body\n"
               b"From b Tue Jan 1 00:00:01 2024\n"
               b"Subject: \x1b[31m SPEC-LIST\n\nbody\n")
        self.check_bytes(raw)

    def test_detect_append_during_scan_without_reading_appended_bytes(self):
        raw = b"From a Tue Jan 1 00:00:00 2024\nSubject: SPEC-LIST\n\nbody\n"
        self.path.write_bytes(raw)
        real_fields = inventory.fields
        modified = [False]
        def mutating_fields(header):
            if not modified[0]:
                modified[0] = True
                with self.path.open("ab") as sink:
                    sink.write(b"unexpected tail")
            yield from real_fields(header)
        with mock.patch.object(inventory, "fields", mutating_fields):
            result = inventory.scan(self.path, 1)
        self.assertFalse(result["stable"])
        self.assertEqual((result["total"], result["selected"]), (1, 1))
        self.assertEqual(result["opened_bytes"], len(raw))

    def test_refusals_are_read_only(self):
        self.path.write_bytes(b"preamble\nFrom a\nSubject: SPEC-LIST\n\n")
        with self.assertRaises(inventory.Refusal):
            inventory.scan(self.path)
        self.path.write_bytes(b"From a\nSubject: " + b"a" * (inventory.HEADER_LIMIT + 1))
        with self.assertRaises(inventory.Refusal):
            inventory.scan(self.path)
        self.path.write_bytes(b"")
        self.assertEqual(inventory.scan(self.path)["total"], 0)
        with self.assertRaises(inventory.Refusal):
            inventory.scan(self.path, 101)
        alias = Path(self.tmp.name) / "symlink"
        alias.symlink_to(self.path)
        with self.assertRaises(OSError):
            inventory.scan(alias)


if __name__ == "__main__":
    unittest.main()
