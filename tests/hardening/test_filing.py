    def test_baseline_backup_corruption_and_failures(self):
        baseline = entry(b"Subject: old archive\n").raw
        self.archive.write_bytes(baseline)
        self.make_plan()
        def corrupt(stage):
            if stage == "archive-backup-close":
                # Flush has already happened, so this modifies the persisted copy.
                path = Path(str(self.plan) + ".transaction/archive.original")
                with path.open("r+b") as stream:
                    stream.seek(len(b"From "))
                    stream.write(b"Y")
        with self.assertRaises(framing.Refusal):
            filing.execute(self.plan, self.root, corrupt)
        self.assertEqual(self.source.read_bytes(), self.original)
        self.assertEqual(self.archive.read_bytes(), baseline)
        filing.execute(self.plan, self.root)
        self.assertEqual(self.archive.read_bytes(), baseline + self.selected)

    def test_actual_fsync_failures_recover(self):
        import shutil
        real_sync = os.fsync
        baseline = entry(b"Subject: older archive\n").raw
        for fail_at in range(1, 24):
            with self.subTest(fsync_call=fail_at):
                self.source.write_bytes(self.original)
                self.archive.write_bytes(baseline)
                self.make_plan()
                calls = 0
                injected = False
                def fail(descriptor):
                    nonlocal calls, injected
                    calls += 1
                    if calls == fail_at:
                        injected = True
                        raise OSError(errno.EIO, "Input/output error (EIO): sync injection")
                    real_sync(descriptor)
                try:
                    with patch.object(os, "fsync", fail):
                        filing.execute(self.plan, self.root)
                except OSError:
                    if self.source.read_bytes() != self.original:
                        self.assertEqual(self.source.read_bytes(), self.kept)
                        self.assertEqual(self.archive.read_bytes(), baseline + self.selected)
                        self.assertEqual(Path(str(self.plan) + ".transaction/source.original").read_bytes(), self.original)
                self.assertTrue(injected, "declared fsync failure point was never reached")
                filing.execute(self.plan, self.root)
                self.assertEqual(self.source.read_bytes(), self.kept)
                self.assertEqual(self.archive.read_bytes(), baseline + self.selected)
                shutil.rmtree(str(self.plan) + ".transaction")

