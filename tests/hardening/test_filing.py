class FilingTests(unittest.TestCase):
    def setUp(self):
        self.temporary = tempfile.TemporaryDirectory()
        self.root = Path(self.temporary.name)
        (self.root / "DISPOSABLE-MAILBOX-TEST-ONLY").touch()
        self.source = self.root / "incoming"
        self.archive = self.root / "archive"
        self.plan = self.root / "plan.tsv"
        self.entries = [entry(b"Subject: SPEC-LIST\nMessage-ID: <same>\n", selected=True), entry(),
                        entry(b"Subject: SPEC-LIST\nMessage-ID: <same>\n", selected=True)]
        self.original = b"".join(x.raw for x in self.entries)
        self.selected = b"".join(x.raw for x in self.entries if x.selected)
        self.kept = b"".join(x.raw for x in self.entries if not x.selected)
        self.source.write_bytes(self.original)

    def tearDown(self):
        self.temporary.cleanup()

    def make_plan(self, mode="move"):
        with self.plan.open("w", encoding="ascii") as stream:
            filing.write_plan(self.source, self.archive, mode, stream)

    def test_policy_independent_of_parser(self):
        for name, entries in cases().items():
            for item in entries:
                with self.subTest(case=name):
                    self.assertEqual(bool(spec_list.evidence(framing.fields(item.header))), item.selected)
        for header in spec_list.SEARCH_HEADERS:
            self.assertTrue(spec_list.evidence([(header, b"SPEC-LIST")]))
            self.assertFalse(spec_list.evidence([(header, b"SPEC LIST")]))
        self.assertFalse(spec_list.evidence([(b"List-ID", b"SPEC-LIST")]))

    def test_corpus_boundaries_bytes_and_selection(self):
        for name, entries in cases().items():
            with self.subTest(case=name):
                raw = b"".join(x.raw for x in entries)
                items = list(framing.records(io.BytesIO(raw)))
                self.assertEqual([(x.start, x.end) for x in items], list(expected_ranges(entries)))
                self.assertEqual([x.envelope for x in items], [x.envelope for x in entries])
                self.assertEqual([x.header for x in items], [x.header for x in entries])
                self.assertEqual([bool(spec_list.evidence(framing.fields(x.header))) for x in items],
                                 [x.selected for x in entries])
                self.assertEqual([x.digest for x in items], [hashlib.sha256(x.raw).hexdigest() for x in entries])
                self.source.write_bytes(raw)
                self.archive.unlink(missing_ok=True)
                self.make_plan("copy")
                # Each corpus copy runs the actual executor, not a stdlib mailbox API.
                filing.execute(self.plan, self.root)
                self.assertEqual(self.archive.read_bytes(), b"".join(x.raw for x in entries if x.selected))
                self.assertEqual(self.source.read_bytes(), raw)
                self.assertEqual(filing.execute(self.plan, self.root), "already-complete")
                import shutil
                shutil.rmtree(str(self.plan) + ".transaction")

    def test_shared_original_fixture_ranges(self):
        import json
        fixtures = Path(__file__).parents[2] / "fixtures"
        manifest = json.loads((fixtures / "manifest.json").read_text())
        for name, contract in manifest["fixtures"].items():
            with self.subTest(case=name), (fixtures / name).open("rb") as stream:
                self.assertEqual(filing.digest_file(fixtures / name), contract["sha256"])
                found = list(framing.records(stream))
                self.assertEqual(len(found), contract["message_count"])
                if "ranges" in contract:
                    self.assertEqual([(x.start, x.end) for x in found],
                                     [tuple(x["whole_entry_range"]) for x in contract["ranges"]])
                if "selected_message_ids" in contract:
                    selected = []
                    for item in found:
                        values = list(framing.fields(item.header))
                        if spec_list.evidence(values):
                            selected.extend(value.decode() for key, value in values if key.lower() == b"message-id")
                    self.assertEqual(selected, contract["selected_message_ids"])

