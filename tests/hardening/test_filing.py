    def test_stale_source_cases(self):
        def append():
            with self.source.open("ab") as stream:
                stream.write(entry().raw)
        mutations = {
            "append": append,
            "replace-inode": lambda: self.replace_source(self.original),
            "shrink": lambda: self.source.write_bytes(self.original[:30]),
            "prefix": lambda: self.source.write_bytes(b"X" + self.original[1:]),
            "metadata": lambda: os.chmod(self.source, 0o640),
        }
        for name, change in mutations.items():
            with self.subTest(change=name):
                self.source.write_bytes(self.original)
                os.chmod(self.source, 0o600)
                self.make_plan()
                change()
                before = self.source.read_bytes()
                with self.assertRaises(framing.Refusal):
                    filing.execute(self.plan, self.root)
                self.assertEqual(self.source.read_bytes(), before)
                self.assertFalse(self.archive.exists())

