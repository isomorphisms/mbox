    def test_permissions_open_and_replace_failures(self):
        self.make_plan()
        original_open = open
        def denied(path, mode="r", *args, **kwargs):
            if str(path).endswith("archive.prepared") and "x" in mode:
                raise PermissionError(errno.EACCES, "Permission denied (EACCES)")
            return original_open(path, mode, *args, **kwargs)
        with patch("builtins.open", denied), self.assertRaises(PermissionError):
            filing.execute(self.plan, self.root)
        self.assertEqual(self.source.read_bytes(), self.original)
        self.assertFalse(self.archive.exists())
        original_replace = os.replace
        def denied_replace(old, new):
            if new == self.source:
                raise PermissionError("source rename denied")
            return original_replace(old, new)
        with patch.object(os, "replace", denied_replace), self.assertRaises(PermissionError):
            filing.execute(self.plan, self.root)
        self.assertEqual(self.source.read_bytes(), self.original)
        self.assertEqual(self.archive.read_bytes(), self.selected)
        filing.execute(self.plan, self.root)
        self.assertEqual(self.source.read_bytes(), self.kept)

    def test_bounded_large_single_line_and_many_messages(self):
        if os.environ.get("MBOX_QUICK"):
            self.skipTest("large resource suite excluded only in mutation subprocesses")
        started = time.monotonic()
        with self.source.open("wb") as stream:
            stream.write(b"From x\nSubject: SPEC-LIST\n\n")
            for _ in range(2048):  # 128 MiB, one body line, no final newline
                stream.write(b"x" * 65536)
        class BoundedReader:
            def __init__(inner, stream): inner.stream = stream
            def readline(inner, size=-1):
                self.assertGreater(size, 0)
                self.assertLessEqual(size, framing.CHUNK)
                return inner.stream.readline(size)
        tracemalloc.start()
        with self.source.open("rb") as stream:
            count = sum(1 for _ in framing.records(BoundedReader(stream)))
        self.make_plan("copy")
        filing.execute(self.plan, self.root)
        peak_one = tracemalloc.get_traced_memory()[1]
        tracemalloc.stop()
        self.assertEqual(count, 1)
        self.assertLess(peak_one, 16 * 1024 * 1024)
        self.assertEqual(filing.digest_file(self.archive), filing.digest_file(self.source))
        import shutil
        shutil.rmtree(str(self.plan) + ".transaction")
        self.archive.unlink()
        with self.source.open("wb") as stream:
            for _ in range(100000):
                stream.write(b"From x\nSubject: SPEC-LIST\n\nbody\n")
        tracemalloc.start()
        self.make_plan("copy")
        peak_many = tracemalloc.get_traced_memory()[1]
        tracemalloc.stop()
        self.assertLess(peak_many, 16 * 1024 * 1024)
        summary = filing.plan_metadata(self.plan)["summary"]
        self.assertEqual(summary[:2], ["100000", "100000"])
        print("RESOURCE single_body=128MiB messages=100000 peak_one=%d peak_many=%d seconds=%.2f" %
              (peak_one, peak_many, time.monotonic() - started))

